"use strict";

const defaultFs = require("fs");
const defaultOs = require("os");
const defaultPath = require("path");
const { applicationId } = require("./custom-applications");

const WEB_BRIDGE_SITES = Object.freeze([
  { key: "claude-web", name: "Claude Web", url: "https://claude.ai/new", processName: "claude-web" },
  { key: "chatgpt-web", name: "ChatGPT Web", url: "https://chatgpt.com/", processName: "chatgpt-web" },
  { key: "gemini-web", name: "Gemini Web", url: "https://gemini.google.com/app", processName: "gemini-web" },
]);

const EXTENSION_FILES = Object.freeze([
  "manifest.json",
  "background.js",
  "content.js",
  "conversation-url.js",
  "icons/icon16.png",
  "icons/icon32.png",
  "icons/icon48.png",
  "icons/icon128.png",
]);

const WEB_BRIDGE_PORTS = Object.freeze([23333, 23334, 23335, 23336, 23337]);
// Filled when the Chrome Web Store listing is public. Empty keeps the current
// in-app unpacked path; capability is the same either way.
const CHROME_WEB_STORE_URL = "";

function chromeWebStoreUrl() {
  return CHROME_WEB_STORE_URL;
}

function listWebBridgeAgents(applications = []) {
  const agents = {};
  for (const site of WEB_BRIDGE_SITES) {
    const found = (applications || []).find((application) => application && (
      application.processName === site.processName || application.name === site.name
    ));
    if (found && typeof found.id === "string" && found.id) agents[site.key] = found.id;
  }
  return agents;
}

function buildWebBridgeDiscovery(applications = [], options = {}) {
  return {
    ok: true,
    app: options.appId || "clawd-on-desk",
    agents: listWebBridgeAgents(applications),
    ports: WEB_BRIDGE_PORTS,
  };
}

function webBridgeBinDir(home, pathApi = defaultPath) {
  return pathApi.join(home, ".clawd-web-bridge", "bin");
}

function webBridgeInstallDir(home, pathApi = defaultPath) {
  return pathApi.join(home, "Library", "Application Support", "AgentHalo", "WebBridge", "extension");
}

function isWebBridgeApplication(application) {
  if (!application || typeof application !== "object") return false;
  return WEB_BRIDGE_SITES.some((site) => (
    application.processName === site.processName || application.name === site.name
  ));
}

function isWebBridgeAgentId(agentId, applications = []) {
  if (typeof agentId !== "string" || !agentId) return false;
  return applications.some((application) => application && application.id === agentId && isWebBridgeApplication(application));
}

function resolveExtensionSource(options = {}) {
  const fsApi = options.fs || defaultFs;
  const pathApi = options.path || defaultPath;
  const candidates = [];
  if (options.sourceDir) candidates.push(options.sourceDir);
  if (options.resourcesPath) {
    candidates.push(pathApi.join(options.resourcesPath, "web-bridge-extension"));
  }
  candidates.push(pathApi.join(__dirname, "..", "..", "agenthalo-web-bridge", "extension"));
  candidates.push(pathApi.join(__dirname, "..", "resources", "web-bridge-extension"));
  for (const candidate of candidates) {
    if (!candidate) continue;
    try {
      if (fsApi.existsSync(pathApi.join(candidate, "manifest.json"))) return candidate;
    } catch { /* try next */ }
  }
  return null;
}

function stubScript(site, platform) {
  if (platform === "win32") {
    return `@echo off\r\nstart "" "${site.url}"\r\n`;
  }
  return `#!/bin/sh\n# AgentHalo Web Bridge launcher stub: opens ${site.name}\nopen "${site.url}"\n`;
}

function writeLauncherStubs(options = {}) {
  const fsApi = options.fs || defaultFs;
  const pathApi = options.path || defaultPath;
  const platform = options.platform || process.platform;
  const home = options.home || defaultOs.homedir();
  const binDir = webBridgeBinDir(home, pathApi);
  fsApi.mkdirSync(binDir, { recursive: true });
  return WEB_BRIDGE_SITES.map((site) => {
    const exe = pathApi.join(binDir, site.processName);
    fsApi.writeFileSync(exe, stubScript(site, platform), { mode: 0o755 });
    return {
      key: site.key,
      id: applicationId(exe, site.name, platform),
      name: site.name,
      sourcePath: exe,
      executablePath: exe,
      processName: site.processName,
      category: "work",
    };
  });
}

function buildConfigSource(agentIds) {
  const value = (key) => JSON.stringify(agentIds[key] || "");
  return [
    "// AgentHalo custom agent IDs. Regenerated by the in-app Web Bridge setup.",
    "const CLAWD_WEB_BRIDGE_CONFIG = {",
    "  agents: {",
    `    "claude-web": ${value("claude-web")},`,
    `    "chatgpt-web": ${value("chatgpt-web")},`,
    `    "gemini-web": ${value("gemini-web")}`,
    "  },",
    `  ports: ${JSON.stringify(WEB_BRIDGE_PORTS)},`,
    "  workingAfterMs: 2500,",
    "  heartbeatMs: 45000,",
    "  pollMs: 500",
    "};",
    "if (typeof globalThis !== \"undefined\") globalThis.CLAWD_WEB_BRIDGE_CONFIG = CLAWD_WEB_BRIDGE_CONFIG;",
    "",
  ].join("\n");
}

function copyExtensionFiles(sourceDir, installDir, options = {}) {
  const fsApi = options.fs || defaultFs;
  const pathApi = options.path || defaultPath;
  fsApi.mkdirSync(installDir, { recursive: true });
  for (const relative of EXTENSION_FILES) {
    const from = pathApi.join(sourceDir, relative);
    const to = pathApi.join(installDir, relative);
    fsApi.mkdirSync(pathApi.dirname(to), { recursive: true });
    fsApi.copyFileSync(from, to);
  }
}

function inspectWebBridgeInstall(options = {}) {
  const fsApi = options.fs || defaultFs;
  const pathApi = options.path || defaultPath;
  const home = options.home || defaultOs.homedir();
  const installDir = options.installDir || webBridgeInstallDir(home, pathApi);
  const manifestPath = pathApi.join(installDir, "manifest.json");
  const configPath = pathApi.join(installDir, "config.js");
  let version = null;
  let filesReady = false;
  try {
    const manifest = JSON.parse(fsApi.readFileSync(manifestPath, "utf8"));
    if (manifest && typeof manifest.version === "string") version = manifest.version;
    filesReady = EXTENSION_FILES.every((relative) => {
      try { return fsApi.existsSync(pathApi.join(installDir, relative)); }
      catch { return false; }
    }) && fsApi.existsSync(configPath);
  } catch {
    filesReady = false;
  }
  return { installDir, filesReady, version };
}

function installWebBridgeFiles(options = {}) {
  const sourceDir = resolveExtensionSource(options);
  if (!sourceDir) {
    return { status: "error", message: "Web Bridge extension files were not found in this app." };
  }
  const pathApi = options.path || defaultPath;
  const home = options.home || defaultOs.homedir();
  const installDir = options.installDir || webBridgeInstallDir(home, pathApi);
  copyExtensionFiles(sourceDir, installDir, options);
  const applications = writeLauncherStubs(options);
  const agentIds = Object.fromEntries(applications.map((application) => [application.key, application.id]));
  const fsApi = options.fs || defaultFs;
  fsApi.writeFileSync(pathApi.join(installDir, "config.js"), buildConfigSource(agentIds));
  return {
    status: "ok",
    sourceDir,
    installDir,
    applications,
    storeUrl: chromeWebStoreUrl(),
    version: inspectWebBridgeInstall({ ...options, installDir }).version,
  };
}

function buildWebBridgeCommit(snapshot, applications) {
  const current = Array.isArray(snapshot && snapshot.customApplications) ? snapshot.customApplications : [];
  const existingByProcess = new Map();
  for (const entry of current) {
    if (entry && isWebBridgeApplication(entry) && entry.processName) {
      existingByProcess.set(entry.processName, entry);
    }
  }
  const nextApps = applications.map((application) => {
    const { key: _key, ...rest } = application;
    const existing = existingByProcess.get(application.processName);
    if (existing && existing.id) {
      return {
        ...existing,
        name: rest.name,
        sourcePath: rest.sourcePath,
        executablePath: rest.executablePath,
        processName: rest.processName,
        category: rest.category || existing.category || "work",
      };
    }
    return rest;
  });
  const kept = current.filter((entry) => !isWebBridgeApplication(entry));
  const customApplications = [...kept, ...nextApps];
  const agents = snapshot && snapshot.agents && typeof snapshot.agents === "object" ? { ...snapshot.agents } : {};
  for (const application of nextApps) {
    agents[application.id] = {
      enabled: true,
      notificationHookEnabled: true,
      ...(agents[application.id] || {}),
      integrationInstalled: false,
      permissionsEnabled: false,
    };
  }
  return { customApplications, agents };
}

function ensureWebBridgeApplications(options = {}) {
  const snapshot = options.snapshot || {};
  const applications = writeLauncherStubs(options);
  const existing = listWebBridgeAgents(snapshot.customApplications || []);
  const missing = WEB_BRIDGE_SITES.some((site) => !existing[site.key]);
  if (!missing) {
    return {
      status: "ok",
      changed: false,
      applications,
      agents: existing,
      storeUrl: chromeWebStoreUrl(),
    };
  }
  return {
    status: "ok",
    changed: true,
    applications,
    agents: listWebBridgeAgents(buildWebBridgeCommit(snapshot, applications).customApplications),
    storeUrl: chromeWebStoreUrl(),
    commit: buildWebBridgeCommit(snapshot, applications),
  };
}

function summarizeWebBridgeConnection(options = {}) {
  const filesReady = options.filesReady === true;
  const registered = Array.isArray(options.applications) && options.applications.length >= WEB_BRIDGE_SITES.length;
  const installations = Array.isArray(options.installations) ? options.installations : [];
  const browserLoaded = installations.some((item) => item && item.status === "installed");
  const browserDisabled = !browserLoaded && installations.some((item) => item && item.status === "disabled");
  const connected = options.connected === true
    || (Array.isArray(options.recentEvents) && options.recentEvents.some((event) => (
      event && event.route === "state" && event.outcome === "accepted"
    )));
  let connection = "idle";
  if (connected && registered) connection = "connected";
  else if (browserLoaded && registered) connection = "browser";
  else if (browserDisabled && registered) connection = "disabled";
  else if (filesReady && registered) connection = "prepared";
  else if (registered) connection = "registered";
  else if (filesReady) connection = "files";
  return {
    filesReady,
    registered,
    browserLoaded,
    connected: connection === "connected",
    connection,
  };
}

function extensionsPageUrl(browser) {
  const name = String(browser || "").toLowerCase();
  if (name.includes("edge")) return "edge://extensions";
  return "chrome://extensions";
}

